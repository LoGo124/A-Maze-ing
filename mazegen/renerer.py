class Renderer:
    def __init__(self, config: dict):
        self.config = config


    def render_maze(self, maze: Maze) -> None:
        maze_str = ""
        for y in range(maze.height):
            for x in range(maze.width):
                cell = maze.get_cell(x, y)
                maze_str += HEX_CELL_TO_ANSI_BLOCK[cell.hex_cell][0]
            maze_str += "\n"
            for x in range(maze.width):
                cell = maze.get_cell(x, y)
                maze_str += HEX_CELL_TO_ANSI_BLOCK[cell.hex_cell][1]
            maze_str += "\n"
            if y == maze.height - 1:  # or True:
                for x in range(maze.width):
                    cell = maze.get_cell(x, y)
                    maze_str += HEX_CELL_TO_ANSI_BLOCK[cell.hex_cell][2]
                maze_str += "\n"
        print(maze_str)
